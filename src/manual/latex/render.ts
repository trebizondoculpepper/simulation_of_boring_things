import type { Block, Chapter, Column, Manual } from '../logic/document';

/**
 * The manual as LuaLaTeX source: an A4 contractor's document of around
 * 2000, in TeX Gyre Heros, with a cover, a document control page, the
 * foreword, contents, then its chapters; a title block at the foot of
 * every page (document number, revision, page of pages). Figures are
 * PDFs in `figures/`. Every string from the model is escaped. Pure.
 */

const SPECIAL: Record<string, string> = {
  '\\': '\\textbackslash{}',
  '{': '\\{',
  '}': '\\}',
  $: '\\$',
  '&': '\\&',
  '#': '\\#',
  '%': '\\%',
  _: '\\_',
  '^': '\\textasciicircum{}',
  '~': '\\textasciitilde{}',
};

/** Plain text, safe in LaTeX. Unicode (°, ×, ₂, →) is left to LuaLaTeX. */
export function escapeLatex(text: string): string {
  return text.replace(/[\\{}$&#%_^~]/g, (c) => SPECIAL[c]);
}

const e = escapeLatex;

function columnSpec(columns: readonly Column[]): string {
  return columns
    .map((c) =>
      c.width
        ? `>{\\raggedright\\arraybackslash}p{${c.width.toFixed(2)}\\linewidth}`
        : c.align === 'right'
          ? 'r'
          : c.align === 'centre'
            ? 'c'
            : 'l',
    )
    .join(' ');
}

function block(b: Block): string {
  switch (b.kind) {
    case 'heading':
      return `\\section{${e(b.text)}}`;
    case 'para':
      return `${e(b.text)}\n`;
    case 'list':
      return [
        '\\begin{itemize}',
        ...b.items.map((i) => `  \\item ${e(i)}`),
        '\\end{itemize}',
      ].join('\n');
    case 'steps':
      return [
        '\\begin{enumerate}',
        ...b.items.map((i) => `  \\item ${e(i)}`),
        '\\end{enumerate}',
      ].join('\n');
    case 'table':
      return [
        '{\\small\\setlength{\\tabcolsep}{4pt}',
        `\\begin{longtable}{${columnSpec(b.columns)}}`,
        `\\caption{${e(b.caption)}}\\\\`,
        '\\toprule',
        `${b.columns.map((c) => `\\textbf{${e(c.head)}}`).join(' & ')} \\\\`,
        '\\midrule',
        '\\endhead',
        ...b.rows.map((r) => `${r.map(e).join(' & ')} \\\\`),
        '\\bottomrule',
        '\\end{longtable}}',
      ].join('\n');
    case 'figure':
      return [
        '\\begin{figure}[htbp]',
        '\\centering',
        `\\includegraphics[width=${b.width.toFixed(2)}\\linewidth,height=0.75\\textheight,keepaspectratio]{figures/${b.file}.pdf}`,
        `\\caption{${e(b.caption)}}`,
        '\\end{figure}',
      ].join('\n');
    case 'warning':
      return [
        `\\begin{warning}{${e(b.title)}}`,
        e(b.text),
        '\\end{warning}',
      ].join('\n');
  }
}

const chapter = (c: Chapter) =>
  [
    `\\chapter{${e(c.title)}}`,
    `\\label{ch:${c.id}}`,
    ...c.blocks.map(block),
  ].join('\n\n');

