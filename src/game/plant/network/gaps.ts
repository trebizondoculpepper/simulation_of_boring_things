/**
 * The gaps in the model: every placeholder in the plant network, grouped
 * by what is missing, so the work left is a list the code produces rather
 * than one someone remembers. Pure.
 */
import { isPlaceholder } from './types';
import type { Aspect, PlantNetwork } from './types';

export interface Gap {
  /** The node's asset ID or the pipe's link ID. */
  where: string;
  /** What it is: the node's name, or the pipe's ends. */
  what: string;
  aspect: Aspect;
  missing: string;
}

export function modelGaps(net: PlantNetwork): Gap[] {
  const gaps: Gap[] = [];
  for (const n of net.nodes)
    for (const [aspect, status] of Object.entries(n.aspects))
      if (isPlaceholder(status))
        gaps.push({
          where: n.id,
          what: n.name,
          aspect: aspect as Aspect,
          missing: status.placeholder,
        });
  for (const l of net.links)
    for (const [aspect, status] of Object.entries(l.aspects ?? {}))
      if (isPlaceholder(status))
        gaps.push({
          where: l.id,
          what: `pipe ${l.from} to ${l.to}`,
          aspect: aspect as Aspect,
          missing: status.placeholder,
        });
  return gaps;
}

/** The gaps by what is missing, the largest first. */
export function gapsByMissing(gaps: readonly Gap[]) {
  const groups = new Map<string, Gap[]>();
  for (const g of gaps)
    groups.set(g.missing, [...(groups.get(g.missing) ?? []), g]);
  return [...groups.entries()].sort((a, b) => b[1].length - a[1].length);
}

/** The gaps as a Markdown report, one paragraph per line. */
export function gapsReport(net: PlantNetwork): string {
  const gaps = modelGaps(net);
  const lines = [
    '# Gaps in the plant model',
    '',
    'Generated by `scripts/model-gaps.test.ts` from the plant network (`src/game/plant/network/`). Do not edit: fill a gap in the model and rerun (`MODEL_GAPS=1 npx vp test run scripts/model-gaps.test.ts`).',
    '',
    `Every placeholder in the network: ${gaps.length} in all, over ${net.nodes.length} nodes and ${net.links.length} pipes. A placeholder still passes its flow, so the network around it works; each one is something the model does not yet simulate.`,
    '',
  ];
  for (const [missing, group] of gapsByMissing(gaps)) {
    lines.push(
      `## ${missing[0].toUpperCase()}${missing.slice(1)} (${group.length})`,
      '',
    );
    for (const g of group)
      lines.push(`- \`${g.where}\`: ${g.what} (${g.aspect})`);
    lines.push('');
  }
  return lines.join('\n');
}
