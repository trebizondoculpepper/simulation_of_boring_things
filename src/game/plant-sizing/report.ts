import { ASSUME, LEVELS } from './sizing';
import type { PlantSizing } from './sizing';

/**
 * The plant sizing as a Markdown report: the totals, each circuit and
 * hall, the machinery to buy, the rooms to build with their sizes and
 * levels, and the assumptions. Pure.
 */

const f = (v: number, digits = 1) => v.toFixed(digits);
const table = (head: string[], rows: (string | number)[][]) =>
  [
    `| ${head.join(' | ')} |`,
    `| ${head.map(() => '---').join(' | ')} |`,
    ...rows.map((r) => `| ${r.join(' | ')} |`),
  ].join('\n');

export function sizingReport(plan: PlantSizing): string {
  const { circuits, halls, rooms, totals } = plan;
  const out: string[] = [];
  out.push('# Plant sizing');
  out.push('');
  out.push(
    'Generated by `scripts/plant-sizing.test.ts` from `src/game/plant-sizing/pools.config.ts`. Do not edit: change the pools or the assumptions and rerun. A designer’s first pass, for proportions and counts, not a real building.',
  );
  out.push('');
  out.push('## Totals');
  out.push('');
  out.push(
    table(
      ['', ''],
      [
        ['Circulation, all pools', `${f(totals.flow)} m³/h`],
        ['Heat to the pools', `${f(totals.poolHeat)} kW`],
        [
          'Heat to the halls’ air (after heat recovery)',
          `${f(totals.airHeat)} kW`,
        ],
        [
          'Boilers',
          `${totals.boilers} × ${ASSUME.boilerOutput} kW (one standby)`,
        ],
        [
          'Air handling',
          `${Math.round(totals.airflow)} m³/h in ${totals.ahus} units`,
        ],
        ['Electrical load, estimated', `${f(totals.load, 0)} kW`],
        ['Sodium hypochlorite used', `${f(totals.hypoLitresPerDay)} l/day`],
        ['Acid used', `${f(totals.acidLitresPerDay)} l/day`],
      ],
    ),
  );
  out.push('');
  out.push('## Water circuits');
  out.push('');
  out.push(
    table(
      [
        'Pool',
        'Use',
        'Volume m³',
        'Flow m³/h',
        'Filters',
        'Pump kW',
        'Evaporation kg/h',
        'Heat kW',
        'Balance tank m³',
      ],
      circuits.map((c) => [
        c.body.name,
        c.body.use,
        f(c.body.volume),
        f(c.flow),
        c.flow < ASSUME.packageBelow
          ? 'packaged set'
          : `${c.filters.count} × ${c.filters.diameter} m`,
        f(c.pumpPower, 2),
        f(c.evaporation, 2),
        f(c.heat),
        c.flow < ASSUME.packageBelow ? 'surge vessel in set' : f(c.balanceTank),
      ]),
    ),
  );
  out.push('');
  out.push('## Halls’ air');
  out.push('');
  out.push(
    table(
      [
        'Hall',
        'Air m³',
        'Air °C',
        'Evaporation kg/h',
        'Air handling m³/h',
        'Set by',
        'Units',
        'Heat kW',
      ],
      halls.map((h) => [
        h.attraction.name,
        h.attraction.hallAir,
        f(h.airTemperature, 0),
        f(h.evaporation, 2),
        Math.round(h.airflow),
        h.drivenBy,
        h.units,
        f(h.heat),
      ]),
    ),
  );
  out.push('');
  out.push('## Shared rings');
  out.push('');
  out.push(
    'Each pool keeps its own water, in its own plant room; these are what they share, run from the main plant to every room.',
  );
  out.push('');
  out.push(
    table(
      ['Service', 'From', 'Serves', 'Flow m³/h', 'Bore', 'Notes'],
      plan.rings.map((r) => [
        r.name,
        r.from,
        r.serves.join(', '),
        r.flow ? f(r.flow) : '',
        `DN${r.dn}`,
        r.note,
      ]),
    ),
  );
  out.push('');
  out.push('## Machinery');
  out.push('');
  const kinds = new Map<string, { count: number; sizes: Set<string> }>();
  for (const r of rooms)
    for (const m of r.machines) {
      const k = kinds.get(m.kind) ?? { count: 0, sizes: new Set<string>() };
      k.count++;
      k.sizes.add(`${f(m.w)} × ${f(m.d)} × ${f(m.h)} m`);
      kinds.set(m.kind, k);
    }
  out.push(
    table(
      ['Machine', 'Count', 'Sizes (w × d × h)'],
      [...kinds]
        .sort((a, b) => b[1].count - a[1].count)
        .map(([k, v]) => [k, v.count, [...v.sizes].join('; ')]),
    ),
  );
  out.push('');
  out.push('## Rooms');
  out.push('');
  out.push(
    table(
      [
        'Room',
        'Level',
        'Plan m',
        'Area m²',
        'Height needed m',
        'Storeys',
        'Why this level',
      ],
      [...rooms]
        .sort((a, b) => a.level - b.level || b.area - a.area)
        .map((r) => [
          r.name,
          r.level,
          `${f(r.w)} × ${f(r.d)}`,
          f(r.area, 0),
          f(r.height),
          r.storeys,
          r.why,
        ]),
    ),
  );
  out.push('');
  out.push(
    `Levels are numbered from 0, the lowest, to ${LEVELS - 1}; a storey is ${ASSUME.storey} m. A room needing two storeys rises through the level above its own.`,
  );
  out.push('');
  for (const r of rooms) {
    out.push(`### ${r.name}`);
    out.push('');
    if (r.needs.length) out.push(`Needs: ${r.needs.join('; ')}.`, '');
    out.push(
      table(
        ['Machine', 'Which', 'w × d × h m', 'Rating'],
        r.machines.map((m) => [
          m.kind,
          m.name,
          `${f(m.w)} × ${f(m.d)} × ${f(m.h)}`,
          m.rating ?? '',
        ]),
      ),
    );
    out.push('');
  }
  out.push('## Assumptions');
  out.push('');
  out.push('```json');
  out.push(JSON.stringify(ASSUME, null, 2));
  out.push('```');
  out.push('');
  return out.join('\n');
}
